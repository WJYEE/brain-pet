/** Resolves a pet id's idle PNG path via the registry — never hardcode the path string directly. */
export function characterIdlePath(id: string): string {
  const asset = CHARACTER_ASSETS[id]
  if (!asset?.animations.idle) throw new Error(`Unknown character asset id: ${id}`)
  return asset.animations.idle
}
